def rune_icons(version):
    """{rune or tree id: Data Dragon image path}; on a network failure, the ones of the data.js already built."""
    try:
        url = "https://ddragon.leagueoflegends.com/cdn/%s/data/en_US/runesReforged.json" % version
        trees = json.loads(urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "rol-site"}),
                                                  timeout=30).read().decode("utf-8"))
        out = {}
        for tree in trees:
            out[tree["id"]] = tree["icon"]
            for slot in tree["slots"]:
                for r in slot["runes"]:
                    out[r["id"]] = r["icon"]
        return out
    except (OSError, ValueError, KeyError):
        try:
            old = open(os.path.join(SITE, "data.js"), encoding="utf-8").read()
            old = json.loads(old[old.index("{"):old.rindex("}") + 1])
            return {int(k): v for k, v in ((old.get("rbuild") or {}).get("icons") or {}).items()}
        except (OSError, ValueError):
            return {}


def build_rbuild(stats):
    """The random build of the app (randombuild.py), for the site: the same rules, drawn in the browser, never
    imported. Names in both languages, images from Data Dragon."""
    sys.path.insert(0, ROOT)
    import randombuild
    import live
    runes = json.load(open(os.path.join(DATA, "runes.json"), encoding="utf-8"))
    items = json.load(open(os.path.join(DATA, "items.json"), encoding="utf-8"))["items"]
    en = json.load(open(os.path.join(DATA, "en", "names.json"), encoding="utf-8"))
    names = lambda fr, en_name: {"fr": fr, "en": en_name or fr}
    rune_names = {int(k): names(v["name"], en["runes"].get(k)) for k, v in runes["runes"].items()}
    trees = {int(k): {"name": names(v["name"], en["trees"].get(k)), "slots": v["slots"]}
             for k, v in runes["trees"].items() if len(v.get("slots") or []) == 4}
    spells = list(randombuild.SPELLS) + [randombuild.SMITE]
    kinds = {"boots": [], "legendary": []}
    for i, v in items.items():
        if v.get("kind") in kinds:
            kinds[v["kind"]].append(int(i))
    item_names = {int(i): names(items[str(i)]["name"], en["items"].get(str(i))) for ids in kinds.values() for i in ids}
    # the starting sets of each role's guides (as core.Data.builds reads them), with the role item when there is one
    starts = {r: [] for r in ROLES}
    for c in stats["combos"].values():
        counts = {i: n for i, n in ((c.get("items") or {}).get("start") or [])}
        for b in c.get("builds") or []:
            uniq, n = [], {}
            for i in (b.get("start") or {}).get("ids") or []:
                if i not in n:
                    uniq.append(i)
                n[i] = n.get(i, 0) + 1
            st = {"ids": uniq, "counts": [n[i] if n[i] > 1 else counts.get(i, 1) for i in uniq]}
            role_items = randombuild.ROLE_ITEMS.get(c["role"])
            if uniq and st not in starts[c["role"]] and (not role_items or role_items & set(uniq)):
                starts[c["role"]].append(st)
    for i in {i for s in starts.values() for st in s for i in st["ids"]}:
        if str(i) in items:
            item_names[i] = names(items[str(i)]["name"], en["items"].get(str(i)))
    return {
        "trees": trees, "runes": rune_names, "icons": rune_icons(stats["meta"].get("ddragon")),
        "shard_rows": runes["shard_rows"],
        "shards": {int(k): names(v, SHARDS_EN.get(int(k))) for k, v in runes["shards"].items()},
        "spells": list(randombuild.SPELLS), "smite": randombuild.SMITE,
        "spell_info": {s: {"image": runes["sums"][str(s)]["image"], "name": names(runes["sums"][str(s)]["name"], en["sums"].get(str(s)))}
                       for s in spells},
        "boots": sorted(kinds["boots"]), "legendary": sorted(kinds["legendary"]), "items": item_names,
        "groups": [sorted(g) for g in randombuild.GROUPS], "no_boots": sorted(randombuild.NO_BOOTS),
        "slot_roles": sorted(randombuild.SLOT_ROLES), "starts": starts,
        "default_start": randombuild.DEFAULT_START,
        "no_skills": sorted(live.NO_SKILLS), "free_ranks": sorted(live.FREE_RANKS), "auto_r": sorted(live.AUTO_R),
        "auto_first": live.AUTO_FIRST,
    }


def build_strings():
    src = open(os.path.join(SITE, "site.js"), encoding="utf-8").read()
    keys = sorted({json.loads('"' + m + '"') for m in re.findall(r'\bt\("((?:[^"\\]|\\.)*)"', src)})
    app = json.load(open(os.path.join(UI, "i18n", "en.json"), encoding="utf-8"))
    own_path = os.path.join(SITE, "strings_en.json")
    own = json.load(open(own_path, encoding="utf-8")) if os.path.exists(own_path) else {}
    norm = lambda s: s.replace("\xa0", " ").replace(" ", " ")
    app_norm = {norm(k): v for k, v in app.items()}
    out, missing = {}, []
    for k in keys:
        v = own.get(k) or app.get(k) or app_norm.get(norm(k))
        if v is None:
            missing.append(k)
        else:
            out[k] = v
    write_js(os.path.join(SITE, "en.js"), "ROL_EN", out)
    return len(out), missing


def copy_assets():
    css = open(os.path.join(UI, "app.css"), encoding="utf-8").read()
    css = css.replace('url("/fonts/', 'url("fonts/').replace("url('/fonts/", "url('fonts/")
    with open(os.path.join(SITE, "app.css"), "w", encoding="utf-8") as f:
        f.write("/* Copy of ui/app.css made by build_site.py: edit the original, then run the script again. */\n")
        f.write(css)
    os.makedirs(os.path.join(SITE, "fonts"), exist_ok=True)
    for fn in ("MarcellusSC-Regular.ttf", "Cinzel-700.ttf", "Cinzel-800.ttf", "OFL-MarcellusSC.txt", "OFL-Cinzel.txt"):
        shutil.copy2(os.path.join(DATA, "fonts", fn), os.path.join(SITE, "fonts", fn))
    shutil.rmtree(os.path.join(SITE, "bg"), ignore_errors=True)
    shutil.copytree(os.path.join(UI, "bg"), os.path.join(SITE, "bg"))
    os.makedirs(os.path.join(SITE, "img", "roles"), exist_ok=True)
    for fn in ("app.png", "logo_base.png", "logo_wheel.png", "logo_pointer.png"):
        shutil.copy2(os.path.join(DATA, "img", fn), os.path.join(SITE, "img", fn))
    for fn in os.listdir(os.path.join(DATA, "img", "roles")):
        shutil.copy2(os.path.join(DATA, "img", "roles", fn), os.path.join(SITE, "img", "roles", fn))


def stamp_assets():
    """index.html links its styles and scripts with a hash of their content (app.css?v=...): browsers keep files in
    cache for a while, and a new version must not show with the previous style or code."""
    path = os.path.join(SITE, "index.html")
    html = open(path, encoding="utf-8").read()
    for name in ("app.css", "site.css", "data.js", "en.js", "site.js"):
        with open(os.path.join(SITE, name), "rb") as f:
            digest = hashlib.sha256(f.read()).hexdigest()[:10]
        html = re.sub(r'(["/])%s(\?v=[0-9a-f]+)?"' % re.escape(name), r'\g<1>%s?v=%s"' % (name, digest), html)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(html)


def build_pages():
    """en/index.html from the French page, then the sitemap (both pages, with their language alternates)."""
    stamp_assets()
    html = open(os.path.join(SITE, "index.html"), encoding="utf-8").read()
    for fr, en in PAGE_EN:
        if fr not in html:
            raise SystemExit("index.html no longer contains: %s" % fr)
        html = html.replace(fr, en)
    # relative files of the English page live one folder up
    html = re.sub(r'((?:href|src)=")(?!https?:|#|/|\.\./)', r"\1../", html)
    os.makedirs(os.path.join(SITE, "en"), exist_ok=True)
    with open(os.path.join(SITE, "en", "index.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(html)
    alt = "".join('\n    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>' % (lang, url)
                  for lang, url in (("fr", SITE_URL), ("en", SITE_URL + "en/"), ("x-default", SITE_URL + "en/")))
    urls = "".join("\n  <url>\n    <loc>%s</loc>%s\n  </url>" % (url, alt) for url in (SITE_URL, SITE_URL + "en/"))
    with open(os.path.join(SITE, "sitemap.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
                'xmlns:xhtml="http://www.w3.org/1999/xhtml">%s\n</urlset>\n' % urls)


def main():
    n, combos = build_data()
    copy_assets()
    k, missing = build_strings()
    build_pages()   # last: links carry the hash of the final files
    print("data.js: %d champions, %d champion + role combos" % (n, combos))
    print("en.js: %d English strings" % k)
    for m in missing:
        print("  missing English: %r" % m)
    print("OK" if not missing else "%d strings without English (add them to strings_en.json)" % len(missing))


if __name__ == "__main__":
    main()
