def write_js(path, var, obj):
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by build_site.py: do not edit by hand.\n")
        f.write("window.%s = %s;\n" % (var, json.dumps(obj, ensure_ascii=False, separators=(",", ":"))))


def build_data():
    stats = json.load(open(os.path.join(DATA, "stats.json"), encoding="utf-8"))
    champs = {}
    for c in stats["combos"].values():
        ch = champs.setdefault(c["key"], {"key": c["key"], "name": c["name"], "name_en": c.get("name_en") or c["name"], "roles": []})
        ch["roles"].append([c["role"], round(c.get("share") or 0, 1)])   # share of the champion's games, in %
    for ch in champs.values():
        ch["roles"].sort(key=lambda r: ROLES.index(r[0]))
    meta = stats["meta"]
    out = {"patch": meta.get("patch"), "generated": meta.get("generated"), "ddragon": meta.get("ddragon"),
           "champions": sorted(champs.values(), key=lambda c: c["name"])}
    write_js(os.path.join(SITE, "data.js"), "ROL_DATA", out)
    return len(champs), sum(len(c["roles"]) for c in champs.values())


def build_strings():
    src = open(os.path.join(SITE, "site.js"), encoding="utf-8").read()
    keys = sorted({json.loads('"' + m + '"') for m in re.findall(r'\bt\("((?:[^"\\]|\\.)*)"', src)})
    app = json.load(open(os.path.join(UI, "i18n", "en.json"), encoding="utf-8"))
    own_path = os.path.join(SITE, "strings_en.json")
    own = json.load(open(own_path, encoding="utf-8")) if os.path.exists(own_path) else {}
    norm = lambda s: s.replace("\xa0", " ").replace(" ", " ")
    app_norm = {norm(k): v for k, v in app.items()}
    out, missing = {}, []
    for k in keys:
        v = own.get(k) or app.get(k) or app_norm.get(norm(k))
        if v is None:
            missing.append(k)
        else:
            out[k] = v
    write_js(os.path.join(SITE, "en.js"), "ROL_EN", out)
    return len(out), missing


def copy_assets():
    css = open(os.path.join(UI, "app.css"), encoding="utf-8").read()
    css = css.replace('url("/fonts/', 'url("fonts/').replace("url('/fonts/", "url('fonts/")
    with open(os.path.join(SITE, "app.css"), "w", encoding="utf-8") as f:
        f.write("/* Copy of ui/app.css made by build_site.py: edit the original, then run the script again. */\n")
        f.write(css)
    os.makedirs(os.path.join(SITE, "fonts"), exist_ok=True)
    for fn in ("MarcellusSC-Regular.ttf", "Cinzel-700.ttf", "Cinzel-800.ttf", "OFL-MarcellusSC.txt", "OFL-Cinzel.txt"):
        shutil.copy2(os.path.join(DATA, "fonts", fn), os.path.join(SITE, "fonts", fn))
    shutil.rmtree(os.path.join(SITE, "bg"), ignore_errors=True)
    shutil.copytree(os.path.join(UI, "bg"), os.path.join(SITE, "bg"))
    os.makedirs(os.path.join(SITE, "img", "roles"), exist_ok=True)
    for fn in ("app.png", "logo_base.png", "logo_wheel.png", "logo_pointer.png"):
        shutil.copy2(os.path.join(DATA, "img", fn), os.path.join(SITE, "img", fn))
    for fn in os.listdir(os.path.join(DATA, "img", "roles")):
        shutil.copy2(os.path.join(DATA, "img", "roles", fn), os.path.join(SITE, "img", "roles", fn))


def build_pages():
    """en/index.html from the French page, then the sitemap (both pages, with their language alternates)."""
    html = open(os.path.join(SITE, "index.html"), encoding="utf-8").read()
    for fr, en in PAGE_EN:
        if fr not in html:
            raise SystemExit("index.html no longer contains: %s" % fr)
        html = html.replace(fr, en)
    # relative files of the English page live one folder up
    html = re.sub(r'((?:href|src)=")(?!https?:|#|/|\.\./)', r"\1../", html)
    os.makedirs(os.path.join(SITE, "en"), exist_ok=True)
    with open(os.path.join(SITE, "en", "index.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(html)
    alt = "".join('\n    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>' % (lang, url)
                  for lang, url in (("fr", SITE_URL), ("en", SITE_URL + "en/"), ("x-default", SITE_URL + "en/")))
    urls = "".join("\n  <url>\n    <loc>%s</loc>%s\n  </url>" % (url, alt) for url in (SITE_URL, SITE_URL + "en/"))
    with open(os.path.join(SITE, "sitemap.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
                'xmlns:xhtml="http://www.w3.org/1999/xhtml">%s\n</urlset>\n' % urls)


def main():
    n, combos = build_data()
    copy_assets()
    build_pages()
    k, missing = build_strings()
    print("data.js: %d champions, %d champion + role combos" % (n, combos))
    print("en.js: %d English strings" % k)
    for m in missing:
        print("  missing English: %r" % m)
    print("OK" if not missing else "%d strings without English (add them to strings_en.json)" % len(missing))


if __name__ == "__main__":
    main()
